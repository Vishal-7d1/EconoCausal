"""
Validation, cleaning and feature engineering for the EconoCausal synthetic data (Member 1).

Run from inside the 01_Dataset_Analysis folder, AFTER generate_synthetic.py:
    python clean_and_engineer.py

Reads : data/synthetic/synthetic_pricing.csv   (raw file is never modified)
Writes: data/processed/synthetic_pricing_clean.csv
        docs/cleaning_report.md

Rules followed:
  * Every check is recorded in the report; nothing is silently changed.
  * Invalid rows are FLAGGED and excluded, with the reason written down.
  * Only information known BEFORE the discount is used for engineered features.
"""
import os
import pandas as pd

RAW = os.path.join("data", "synthetic", "synthetic_pricing.csv")
OUT_DIR = os.path.join("data", "processed")
OUT = os.path.join(OUT_DIR, "synthetic_pricing_clean.csv")
REPORT = os.path.join("docs", "cleaning_report.md")

ALLOWED_DISCOUNTS = {0, 10, 20}
log = []          # lines for the report


def note(text):
    log.append(text)
    print(text)


df = pd.read_csv(RAW)
n_raw = len(df)
note(f"- Raw file: {n_raw} rows, {df.shape[1]} columns")

# ---------- 1. Inspect ----------
missing = df.isna().sum()
note(f"- Missing values: {int(missing.sum())} in total")
for col, cnt in missing[missing > 0].items():
    note(f"  - {col}: {int(cnt)} missing (NOT imputed; rows flagged below)")
note(f"- Fully duplicated rows: {int(df.duplicated().sum())}")
note(f"- Duplicated customer_id values: {int(df['customer_id'].duplicated().sum())}")

# ---------- 2. Validate values (each rule marks rows as bad) ----------
rules = {
    "age outside 18-100": ~df["age"].between(18, 100),
    "monthly_income not positive": ~(df["monthly_income"] > 0),
    "avg_basket_value not positive": ~(df["avg_basket_value"] > 0),
    "past_purchases negative": df["past_purchases"] < 0,
    "days_since_last_purchase negative": df["days_since_last_purchase"] < 0,
    "loyalty_member not 0/1": ~df["loyalty_member"].isin([0, 1]),
    "discount not in {0,10,20}": ~df["discount"].isin(ALLOWED_DISCOUNTS),
    "purchased not 0/1": ~df["purchased"].isin([0, 1]),
    "spend negative": df["spend"] < 0,
    "spend > 0 but purchased = 0": (df["purchased"] == 0) & (df["spend"] > 0),
    "any missing value": df.isna().any(axis=1),
    "duplicate customer_id": df["customer_id"].duplicated(keep="first"),
}
bad = pd.Series(False, index=df.index)
note("\n- Validation rules (rows failing each rule):")
for name, mask in rules.items():
    note(f"  - {name}: {int(mask.sum())}")
    bad |= mask

flagged = df[bad]
if len(flagged):
    os.makedirs(OUT_DIR, exist_ok=True)
    flagged.to_csv(os.path.join(OUT_DIR, "flagged_rows.csv"), index=False)
    note(f"- {len(flagged)} rows excluded; saved to data/processed/flagged_rows.csv")
else:
    note("- No invalid rows found, so no rows were excluded")
df = df[~bad].copy()

# ---------- 3. Standardise types ----------
for col in ["region"]:
    df[col] = df[col].astype(str).str.strip().str.title()
df["region"] = df["region"].astype("category")
note(f"\n- Regions found: {sorted(df['region'].cat.categories)}")

# ---------- 4. Feature engineering (pre-treatment information only) ----------
df["age_group"] = pd.cut(df["age"], bins=[17, 29, 49, 100],
                         labels=["young", "adult", "older"])
df["income_tier"] = pd.cut(df["monthly_income"], bins=[0, 20000, 50000, float("inf")],
                           labels=["low", "medium", "high"])
df["recency_group"] = pd.cut(df["days_since_last_purchase"], bins=[-1, 15, 45, 10**6],
                             labels=["recent", "moderate", "lapsed"])
note("- Engineered: age_group (18-29 young, 30-49 adult, 50+ older), "
     "income_tier (<=20,000 low, 20,001-50,000 medium, >50,000 high), "
     "recency_group (<=15 days recent, 16-45 moderate, >45 lapsed)")

# ---------- 5. Save ----------
os.makedirs(OUT_DIR, exist_ok=True)
df.to_csv(OUT, index=False)
note(f"- Clean file: {len(df)} rows, {df.shape[1]} columns -> {OUT}")

# ---------- 6. Report ----------
X_cols = ["age", "region", "monthly_income", "loyalty_member", "past_purchases",
          "days_since_last_purchase", "avg_basket_value",
          "age_group", "income_tier", "recency_group"]
os.makedirs("docs", exist_ok=True)
with open(REPORT, "w", encoding="utf-8") as f:
    f.write("# Cleaning Report: synthetic_pricing.csv\n\n")
    f.write("Generated by `clean_and_engineer.py`. The raw file is never modified.\n\n")
    f.write("## What was checked and changed\n\n" + "\n".join(log) + "\n\n")
    f.write("## Variable roles for causal modelling\n\n")
    f.write("| Role | Columns |\n|---|---|\n")
    f.write("| X (pre-treatment features) | " + ", ".join(X_cols) + " |\n")
    f.write("| T (treatment) | discount |\n")
    f.write("| Y (outcome) | purchased |\n")
    f.write("| Do NOT use as features | spend (measured after the discount), "
            "customer_id (identifier), everything in synthetic_ground_truth.csv (answer key) |\n")
print("\nReport written to", REPORT)
